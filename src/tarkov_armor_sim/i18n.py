def normalize_locale(value: str | None) -> str:
    if value and value != "system":
        return "zh_CN" if value.lower().startswith("zh") else "en_US"
    requested = os.getenv("EFT_CALCULATOR_LANG")
    if requested:
        return normalize_locale(requested)
    detected = system_locale.getlocale()[0] or ""
    return "zh_CN" if detected.lower().startswith("zh") else "en_US"


class I18n:
    def __init__(self, locale: str | None = None) -> None:
        self.locale = normalize_locale(locale)
        self._english_to_source = {value: key for key, value in EN_US.items()}

    def set_locale(self, locale: str) -> None:
        self.locale = normalize_locale(locale)

    def translate(self, source: str, **values: object) -> str:
        canonical = self._english_to_source.get(source, source)
        translated = EN_US.get(canonical, canonical) if self.locale == "en_US" else canonical
        return translated.format(**values) if values else translated
